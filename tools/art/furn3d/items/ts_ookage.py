# ツチノオオカゲ（tsookage、土のステージの大きな影）：岩とかげの、大きなゆりかご。ゆっくり左右にゆれる（8コマ）。村の夜に来る（js/tsuchi.js の tsOokDraw）。
# 設計図（単位はマス。x=東・y=南・z=上。絵のまん中のマスの左上が(0,0)。まん中は (0.5,0.5)）
#   ゆり木：東西にのびる、そりかえった岩の木2本（tube、太さ0.05。y=0.04 と 0.96、x=−0.95〜1.95、両はしが0.40上がる）。
#   かご：だ円の岩のかご（egg：よこ0.92・おく0.40・たて0.30、まん中の高さ0.44）。口のふち（ひらたい egg、明るい岩）と、口の中のかげ（紫の灰色）。南の面に、岩のひび（こい色の短いすじ4本）。
#   ほろ：西のはしに、まるい岩のほろ（egg：0.34・0.40・0.38）。東むきに口をあけ（中のくぼみ：紫の灰色）、くぼみの中に、金色の目2つ（ball、半径0.05）。
#   かげ：口から、ゆるい波でのぼる、かげのすじ4本。下は太く（0.04）・上へ細く（0.018）・上ほど明るい紫。コマでは、形をかえずに少しなびくだけ。
#   ゆれ：組んだ3Dを まるごと ±6度、ゆり木がゆかの上をころがるように まわす（EXTRA）。
import math
import numpy as np
from blueprint import Part as P
ID='tsookage';TONE5=True;DITHER=0;BOTTOM=60;FRAMES=8;FR=0
VIEWS=[('tsookage',0)]
ROCK=(140,124,120);ROCKL=(180,164,150);ROCKD=(84,72,78);RAIL=(112,98,100);INNER=(92,78,112);WISPS=[(110,94,140),(142,128,178),(190,180,222)];EYE=(255,226,150)
RK=0.19   # ゆり木のそり（z=0.05+RK·(x−0.5)²）
def PARTS():
    ph=FR/FRAMES*2*math.pi;L=[]
    for i,y in enumerate((0.04,0.96)):
        pts=[(x,y,0.05+RK*(x-0.5)**2) for x in np.linspace(-0.95,1.95,13)]
        r=P('ゆり木%d'%i,'tube',(pts,0.05),RAIL,on=('ground',),note='地面にふれて、ゆれる');L.append(r)
    L+=[P('かご','egg',(0.50,0.50,0.44,0.92,0.40,0.30,0),ROCK,on=('ゆり木0','ゆり木1'),note='ゆり木の上'),
        P('ふち','egg',(0.56,0.50,0.68,0.74,0.32,0.05,0),ROCKL,on=('かご',),note='かごの口'),
        P('口のかげ','egg',(0.58,0.50,0.705,0.64,0.26,0.035,0),INNER,on=('ふち',),note='口の中'),
        P('ほろ','egg',(-0.18,0.50,0.80,0.34,0.40,0.38,0),ROCK,on=('かご',),note='西のはし'),
        P('ほろの口','egg',(0.00,0.52,0.80,0.18,0.30,0.28,0),INNER,on=('ほろ',),note='東むきの、くぼみ')]
    for i,y in enumerate((0.40,0.62)):L.append(P('目%d'%i,'ball',(0.17,y,0.84,0.05),EYE,on=('ほろの口',),note='金色の目'))
    for i,(x,z0,z1) in enumerate(((0.0,0.32,0.48),(0.26,0.24,0.40),(0.52,0.22,0.36),(0.78,0.26,0.42),(1.04,0.30,0.46),(1.26,0.36,0.50))):L.append(P('ひび%d'%i,'tube',([(x,0.905,z0),(x+0.04,0.905,(z0+z1)/2),(x+0.01,0.905,z1)],0.02),ROCKD,on=('かご',),note='岩のひび'))
    for i,(x,y) in enumerate(((0.30,0.42),(0.60,0.58),(0.90,0.42),(1.16,0.56))):
        sw=0.03*math.sin(ph+i*0.6);pt=lambda t:(x+0.05*math.sin(t*5.0+i)+sw*t*1.6,y,0.70+0.52*t)
        for k,(t0,t1,r) in enumerate(((0.0,0.34,0.04),(0.34,0.67,0.03),(0.67,1.0,0.018))):
            L.append(P('かげ%d-%d'%(i,k),'tube',([pt(t0+(t1-t0)*q) for q in (0,0.25,0.5,0.75,1)],r),WISPS[k],on=('口のかげ',),note='ゆるい波でのぼる'))
    for p in L:p.tex=False
    return L
def EXTRA(sc):   # ゆり木が、ゆかの上をころがる：そりのまるみの中心（x=0.5・z=Rc）のまわりに まわし、ころがった分だけ東西へずらす（ゆり木のいちばん下が、いつも地面にふれる）
    a=math.radians(6*math.sin(FR/FRAMES*2*math.pi));c,s=math.cos(a),math.sin(a);Rc=1/(2*RK)
    R=lambda v:np.array([0.5+c*(v[0]-0.5)-s*(v[2]-Rc)-Rc*a,v[1],Rc+s*(v[0]-0.5)+c*(v[2]-Rc)])
    sc.t=[(R(p),R(q),R(d),col,pid) for p,q,d,col,pid in sc.t]
