# すべり台（slide）：いまの絵と同じデザイン・同じ大きさ（2×1マス）。左に手すりつきの階段、まん中に柱4本と手すりの台、右へクリーム色のすべる面。
# 設計図（じっさいに作れる組み方。単位はマス。大きさは、いまの絵（128×96ドット）に合わせた）
#   台：柱4本（まるい木の柱、半径0.045・高さ0〜1.05、x=0.55 と 1.05、y=0.25 と 0.85。てっぺんはまるい）。床板（x=0.55〜1.05・y=0.25〜0.85、高さ0.70〜0.76）を柱にとめる。
#     台の手すり：うしろに横木2本（高さ0.86・0.98）。台の下の前に、横板3まい（高さ0.20・0.36・0.52）。
#   階段：左へおりる階段（はば0.48、6だん、1だんの高さ0.117・おくゆき0.083。x=0.05〜0.55、高さ0〜0.70）。両がわの側板（ささら、あつさ0.03）のあいだに、ふみ板（あつさ0.025）とけこみ板をはめる。
#     手すり：両がわに、地面に立てた支えと台の柱にとめた、ななめの手すり。
#   すべる面：台の右から右下へ（x=1.05〜1.66、高さ0.74 → 0.16）、さいごは平ら（x=1.66〜1.95、高さ0.12〜0.16）。平らな所は木の台（高さ0.10）にのせる。クリーム色の板（はば0.46）、両がわに木のふち（高さ0.14）。下のはしは、木の脚で地面にとめる。
from blueprint import Part as P
from common import *
import math
ID='slide';GRAD=True;BOTTOM=63;SZ=(2,1)
VIEWS=[('slide',0)]
CY=0.55;Y0,Y1=0.25,0.85;CREAM=(250,236,204)
def PARTS():
    L=[]
    for nx,x in(('左',0.55),('右',1.05)):
        for ny,y in(('前',Y1),('うしろ',Y0)):
            L.append(P('柱（%s%s）'%(nx,ny),'lathe',(x,y,[(0.0,0.0),(0.045,0.0),(0.045,1.02),(0.04,1.04),(0.025,1.05),(0.0,1.05)]),WOOD,detail=14,note='地面にうめてたてる'))
    L.append(P('床板','box',(0.55,Y0,0.70,1.05,Y1,0.76),WOOD,bevel=0.01,on=('柱（左前）','柱（右前）','柱（左うしろ）','柱（右うしろ）'),note='柱にとめる'))
    for k,z in enumerate((0.86,0.98)):
        L.append(P('手すり（うしろ%d）'%(k+1),'beam',((0.55,Y0,z),(1.05,Y0,z),0.025),WOOD,on=('柱（左うしろ）','柱（右うしろ）'),note='柱のあいだにとめる'))
    for k,z in enumerate((0.20,0.36,0.52)):   # 台の下の、前の横板
        L.append(P('前の横板%d'%(k+1),'box',(0.55,Y1-0.012,z,1.05,Y1+0.012,z+0.08),WOOD,bevel=0.006,on=('柱（左前）','柱（右前）'),note='前の柱のあいだにとめる'))
    # 階段：左へおりる。両がわの、段の形にきざんだささら板（側板）に、ふみ板とけこみ板をはめる
    N=6;XS,XE=0.05,0.55;ZE=0.70;dx=(XE-XS)/N;dz=ZE/N
    for ny,y in(('前',CY+0.24),('うしろ',CY-0.24)):
        L.append(P('ささら（%s）'%ny,'prism',([(XS,0.0),(XE,ZE-0.18),(XE,ZE-0.09),(XS+0.02,dz-0.05),(XS,dz-0.05)],y-0.015,y+0.015,'y'),WOOD,on=('ground','柱（左前）' if ny=='前' else '柱（左うしろ）'),note='段の形にあわせて切った側板。下は地面、上は柱にとめる'))
        L.append(P('階段の手すり（%s）'%ny,'beam',((XS+0.03,y,dz+0.42),(XE,y,0.98),0.02),WOOD,on=('手すりの支え（%s）'%ny,),note='支えと柱にとめる'))
        L.append(P('手すりの支え（%s）'%ny,'beam',((XS+0.03,y,0.02),(XS+0.03,y,dz+0.44),0.022),WOOD,on=('ground',),note='地面にうめてたてる'))
    for i in range(N):   # 段：けこみ板（たて）とふみ板（よこ）。左から右へ1だんずつ上がる
        x0=XS+dx*i;z1=dz*(i+1)
        L.append(P('けこみ板%d'%(i+1),'box',(x0,CY-0.225,z1-dz,x0+0.012,CY+0.225,z1),WOOD,bevel=0.0,on=('ささら（前）','ささら（うしろ）'),note='ささらのあいだにはめる'))
        L.append(P('ふみ板%d'%(i+1),'box',(x0-0.015,CY-0.235,z1-0.025,x0+dx,CY+0.235,z1),WOOD,bevel=0.006,on=('ささら（前）','ささら（うしろ）'),note='ささらのあいだにはめる'))
    # すべる面：台から右下へすべりおりて、さいごは地面すれすれで平らになる
    a,b,c=(1.05,0.76),(1.66,0.16),(1.95,0.12)
    L.append(notex(P('すべる面','plate',((a[0],CY,a[1]-0.02),(b[0],CY,b[1]),0.46,0.03),CREAM,on=('床板',),note='台の右のはしにかける')))
    L.append(notex(P('すべる面（平ら）','plate',((b[0]-0.01,CY,b[1]),(c[0],CY,c[1]),0.46,0.03),CREAM,on=('すべる面','すべる面の脚'),note='おりる所。平らにして脚にのせる')))
    for ny,y in(('前',CY+0.245),('うしろ',CY-0.245)):
        L.append(P('すべる面のふち（%s）'%ny,'plate',((a[0],y,a[1]+0.04),(b[0],y,b[1]+0.06),0.03,0.14),WOOD,on=('すべる面',),note='すべる面の両がわ'))
        L.append(P('すべる面のふち（平ら・%s）'%ny,'plate',((b[0]-0.02,y,b[1]+0.06),(c[0],y,c[1]+0.06),0.03,0.14),WOOD,on=('すべる面（平ら）',),note='平らな所の両がわ'))
    L.append(P('すべる面の脚','box',(1.70,CY-0.20,0.0,1.92,CY+0.20,0.10),WOOD,bevel=0.006,on=('ground',),note='平らな所をのせる台'))
    return L
