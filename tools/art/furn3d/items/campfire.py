# たき火（campfire）：いまの絵と同じデザイン・同じ大きさ。まるい石をわっかにならべ、中に、まきを組んで火がもえる（3コマでうごく）。
# 設計図（じっさいに作れる組み方。単位はマス。大きさは、いまの絵（58×58ドット）に合わせた）
#   石：まるい石8こ（半径0.142〜0.16、たてに0.6につぶした形）を、まん中から0.32の輪にならべる（となりの石とふれあう）。地面におく。石ごとに少し色がちがう。石のテクスチャ。
#   灰：石の輪の中の地面に、うすい灰のしき（半径0.27・高さ0〜0.02）。
#   まき：皮のついた丸太（半径0.035〜0.04）6本。4本は、さきをまん中に集めて立てかけ（さんかくのテント組み）、2本は下にねかせて交差させる。
#   火：まきのまん中に、いくつもの炎の舌（common.fire）。まん中の大きな舌3本（上でわかれる）・まわりの小さな舌4本・上にうかぶ小さな炎。コマごとに、舌の高さとゆれがかわる。
#   おき火：まきの根もとに、赤く光る小さなつぶ。
from blueprint import Part as P
from common import *
import math
ID='campfire';GRAD=True;BOTTOM=63;FRAMES=3
VIEWS=[('campfire',0)]
FR=0
CX,CY=0.50,0.52;ASH=(168,156,148);EMBER=(255,128,72)
SHADES=[(204,190,178),(190,176,166),(212,198,186),(184,170,160),(198,186,172)]   # あたたかい灰色の石
def PARTS():
    L=[notex(P('灰','lathe',(CX,CY,[(0.0,0.0),(0.27,0.0),(0.26,0.012),(0.0,0.02)]),ASH,detail=32,note='石の輪の中の地面'))]
    N=8
    for i in range(N):
        a=2*math.pi*i/N+0.2;r=0.142+0.018*((i*7)%3)/2;x,y=CX+0.32*math.cos(a),CY+0.32*math.sin(a)*0.92
        s=P('石%d'%(i+1),'ball',(x,y,r*0.6,r,0.6),SHADES[(i*3)%len(SHADES)],note='地面におく');s.stone=True;L.append(s)
    L.append(P('まき（下1）','log',((CX-0.20,CY-0.06,0.04),(CX+0.20,CY+0.08,0.04),0.04),LOG,on=('灰',),note='灰の上にねかせる'))
    L.append(P('まき（下2）','log',((CX-0.18,CY+0.10,0.04),(CX+0.19,CY-0.08,0.04),0.04),LOG,on=('灰',),note='灰の上にねかせる。下1と交差'))
    top=(CX,CY,0.30)
    for k,a in enumerate((30,120,210,300)):   # テント組み：根もとは灰の上、さきはまん中で合わせる
        r_=math.radians(a);b=(CX+0.19*math.cos(r_),CY+0.17*math.sin(r_),0.03)
        L.append(P('まき（立て%d）'%(k+1),'log',(b,top,0.035),LOG,on=('灰','まき（下1）','まき（下2）'),note='さきをまん中で、ほかのまきと合わせて立てかける'))
    for k,(dx,dy) in enumerate(((-0.08,0.10),(0.09,0.09),(0.02,0.13),(-0.11,-0.02))):   # おき火
        e=notex(P('おき火%d'%(k+1),'ball',(CX+dx,CY+dy,0.03,0.025,0.6),EMBER,on=('灰',),note='まきの根もと'));e.glow=True;L.append(e)
    L+=fire('火',CX,CY+0.03,0.04,0.82,0.115,('灰',),fr=FR,seed=1,small=4)   # リアルな火（いくつもの炎の舌。コマごとにかわる）
    return L
