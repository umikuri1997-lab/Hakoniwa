# たき火（campfire）：いまの絵と同じデザイン・同じ比率・同じならび。まるい石をわっかにならべ、中に、まきを放射にねかせて組み、その上で火がもえる（8コマでうごく）。
# 設計図（じっさいに作れる組み方。単位はマス。大きさは、いまの絵（58×58ドット）に合わせた）
#   石：だ円の石10こ（輪にそったよこの半径0.135〜0.15・おくの半径0.095〜0.105・たての半径0.065）を、まん中から0.35の輪にならべる（となりの石とふれあう）。地面におく。石ごとに少し色がちがう。石のテクスチャ。
#   灰：石の輪の中の地面に、うすい灰のしき（半径0.30・高さ0〜0.02）。
#   まき：皮のついた丸太（半径0.038）8本。外のはしは灰の上（まん中から0.27）、内のはしは、まん中へよせて少し上げる（まん中から0.05・高さ0.09）。放射にならべる。
#   火：粒（パーティクル）の火（PFIRE）。まきのまん中から粒が上がり、まん中へよって小さくなり、黄→こがね色→だいだい→赤とかわって消える。火の粉・けむりも上がる。
#     火は、まき・灰の上にかさねる。石だけ、そのうしろの火をかくす（PFIRE_HIDE）。
from blueprint import Part as P
from common import *
import math
ID='campfire';GRAD=True;BOTTOM=63;FRAMES=8
VIEWS=[('campfire',0)]
FR=0
CX,CY=0.50,0.52
PFIRE=[(CX,CY+0.02,0.08,0.74,0.125,180,1)]   # 粒の火（まきのまん中から）
PFIRE_HIDE=lambda n:n.startswith('石')
ASH=(168,156,148);EMBER=(255,128,72)
SHADES=[(204,190,178),(190,176,166),(212,198,186),(184,170,160),(198,186,172)]   # あたたかい灰色の石
def PARTS():
    L=[notex(P('灰','lathe',(CX,CY,[(0.0,0.0),(0.30,0.0),(0.29,0.012),(0.0,0.02)]),ASH,detail=32,note='石の輪の中の地面'))]
    N=10
    for i in range(N):   # だ円の石：高さはそのまま（0.065）、輪にそって横に長く
        a=2*math.pi*i/N+0.15;r=0.10+0.01*((i*7)%3)/2;x,y=CX+0.35*math.cos(a),CY+0.35*math.sin(a)*0.92
        s=P('石%d'%(i+1),'egg',(x,y,0.065,r*1.35,r*0.95,0.065,math.degrees(a)+90),SHADES[(i*3)%len(SHADES)],note='地面におく');s.stone=True;L.append(s)
    for k in range(8):   # まき：放射にならべ、内のはしをまん中へよせて少し上げる
        a=2*math.pi*k/8+0.39;o=(CX+0.27*math.cos(a),CY+0.25*math.sin(a),0.04);i_=(CX+0.05*math.cos(a),CY+0.05*math.sin(a),0.09)
        L.append(P('まき%d'%(k+1),'log',(o,i_,0.038),LOG,on=('灰',),note='外のはしは灰の上、内のはしは、まん中でほかのまきにのせる'))
    for k,(dx,dy) in enumerate(((-0.10,0.12),(0.11,0.11),(0.02,0.16),(-0.14,-0.02))):   # おき火
        e=notex(P('おき火%d'%(k+1),'ball',(CX+dx,CY+dy,0.03,0.022,0.6),EMBER,on=('灰',),note='まきのあいだ'));e.glow=True;L.append(e)
    return L
