# 木のにんぎょう（rel_ningyo）：地下の廃村の食卓のいすに、すわっていた、むかしの道具。かざり。
# お手本：じっさいにある木のにんぎょう「ペグ・ウッデン（ダッチ・ドール）」の作り方（ポリフォークに、にた物はなかった）。
#   頭・首・どうは、1本の木をろくろでけずった1つの部品。うで・足は、まっすぐの丸い棒で、かた・こしを木のピン（くぎ）でとめて動かす。
# 設計図（単位はマス。z=上）
#   どう：ろくろでけずった1本の木（こし 半径0.066・どう 0.060・むね 0.062・首 0.026・頭 0.074・高さ0.02〜0.42）。まっすぐ立てる・かたむけない。
#   脚：まっすぐの丸い棒（半径0.022・長さ0.24）。こしの下のピンでとめ、すわっているので前へたおしてある（地面にのせる）。
#   足：脚の先に、けずり出した足（前0.034・よこ0.03・高さ0.05のたまご形）。すわっているので、つま先は上。
#   かたのピン：どうを横につらぬく木のピン（半径0.008）。そのはしに、うでをとめる。
#   うで：まっすぐの丸い棒（半径0.018）。かたのピンから、どうのよこにそって、まっすぐ下へ（どうの面に、上から下まで0.002〜0.008 くいこむ。すきまを作らない）。先は、へらの形の手。
#   目：頭の前の面にかいた、小さな2つの点（なでられて、ほかの絵はすりへった）。
from blueprint import Part as P
from common import *
import math
ID='rel_ningyo';GRAD=True;BOTTOM=60;OUTERK=True
VIEWS=[('rel_ningyo',0)]
CX,CY=0.47,0.42;WD5=(214,178,128);DK=(110,84,60)
F=(0.42,0.91);SD=(0.91,-0.42)   # 顔は南（前。クォータービューでは左下）から、少しカメラのほうへ（25度）。まっすぐ南だと、目の1つが頭のうらにかくれる：F 前・SD よこ
def at(f,s0,z):return(CX+F[0]*f+SD[0]*s0,CY+F[1]*f+SD[1]*s0,z)
def T(p):p.tex=False;p.curve=True;p.olk=0.9;return p   # 部品のさかいの線はうすく（こい線だと、うでが、ちぎれて見える）。まわりの線は OUTERK でそのまま
BODY=[(0.0,0.02),(0.060,0.02),(0.066,0.05),(0.064,0.09),(0.060,0.14),(0.061,0.19),(0.062,0.22),(0.058,0.25),(0.030,0.265),(0.026,0.28),(0.046,0.295),(0.068,0.32),(0.074,0.35),(0.066,0.385),(0.044,0.41),(0.0,0.42)]
LR,AR,SH,LL=0.022,0.018,0.235,0.24      # 脚の半径・うでの半径・かたのピンの高さ・脚の長さ
def PARTS():
    L=[T(P('どう','lathe',(CX,CY,BODY),WD5,detail=32,note='1本の木をけずる。地面にすわる'))]
    L.append(T(P('こしのピン','tube',([at(0.0,-0.07,LR),at(0.0,0.07,LR)],0.016),WD5,on=('どう',),note='こしの下をよこにつらぬく')))
    for s in(-1,1):
        L.append(T(P('脚%d'%s,'tube',([at(0.0,s*0.032,LR),at(LL,s*0.032,LR)],LR*2),WD5,on=('こしのピン',),note='こしのピンでとめ、前へたおす')))
        L.append(T(P('足先%d'%s,'egg',(*at(LL+0.01,s*0.032,0)[:2],0.05,0.034,0.03,0.05,math.degrees(math.atan2(F[1],F[0]))),WD5,on=('脚%d'%s,),note='脚の先の、けずり出した足。すわっているので、つま先は上')))
    L.append(T(P('かたのピン','tube',([at(0.0,-0.074,SH),at(0.0,0.074,SH)],0.016),WD5,on=('どう',),note='どうをよこにつらぬく')))
    for s in(-1,1):
        x=s*0.077          # うでの棒のまん中：内がわ0.059。どうの半径（0.060〜0.066）に、どこでもくいこむ
