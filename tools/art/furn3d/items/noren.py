# のれん（noren）：いまの絵と同じデザイン・同じ大きさ。温泉の入り口の上にかける、木の竿と、うすい青の布3まい。まん中の布に、温泉のしるし。
# 設計図（じっさいに作れる組み方。単位はマス。大きさは、いまの絵（80×60ドット）に合わせた。入り口の上の高い所にかける）
#   竿：まるい木の竿（半径0.03、x=-0.10〜1.10・高さ1.55）。両はしに、まるい木の玉（半径0.06）。
#   布：うすい青の布3まい（上のはば：まん中0.38・両がわ0.31。上の4分の3はとなりとくっつき、下の4分の1は内がわのはしがせまくなって、布のあいだがひらく（下で0.04））。高さ1.55 → 0.74、あつさ0.012）。布のあいだは0.015あける。上のはしは、輪4つ（両はしと布のさかい目、はば0.09、高さ1.49〜1.60）で竿に通す。
#   しるし：まん中の布に、温泉のしるし（♨：U字の湯船（はば0.29）と、その上に間をあけてならぶ、ゆらゆらの湯気3本（まん中が少し高い）。クリーム色。布の面のもよう）。
from blueprint import Part as P
from common import *
import math
ID='noren';GRAD=True;PARALLEL=True;BOTTOM=-32   # 入り口の上の高い所にかけるので、絵は地面より上（いまの絵と同じ所）
VIEWS=[('noren',0)]
CY=0.55;CLOTH=(168,182,208);MARK=(244,236,214);ZT,ZB=1.55,0.74
def mark(x,y,z):   # 温泉のしるし（♨）：U字の湯船（上があいた、よこ長のだ円の下がわ）と、その上に間をあけてならぶ、ゆらゆらの湯気3本（まん中が少し高い）
    du,dv=(x-0.50)/0.145,(z-1.06)/0.09;a=math.degrees(math.atan2(dv,du))
    if abs(math.hypot(du,dv)-1.0)<0.22 and not(10<a<170):return MARK   # U字の湯船
    for xc,top in((0.42,1.36),(0.50,1.39),(0.58,1.36)):
        if 1.10<z<top:
            t=(z-1.10)/(top-1.10);xw=xc+0.02*math.sin(t*2*math.pi)   # S字に1回ゆれる
            if abs(x-xw)<0.018:return MARK
    return None
def PARTS():
    r=P('竿','frust',((-0.10,CY,ZT),(1.10,CY,ZT),0.03,0.03),WOOD,note='入り口の上の金具にかける（金具は入り口の物）');r.deco=True;L=[r]
    for k,x in enumerate((-0.10,1.10)):L.append(P('竿の玉%d'%(k+1),'ball',(x,CY,ZT,0.06),WOOD,on=('竿',),note='竿のはし'))
    TOP=((0.0,0.31),(0.31,0.69),(0.69,1.0));BOT=((0.0,0.29),(0.33,0.67),(0.71,1.0));ZM=0.96   # 布：上半分はとなりとくっつき、下の4分の1（ZM 0.96 より下）は内がわのはしがせまくなって、すきまがひらく   # 布：上はとなりとくっつき、下へいくほど内がわのはしがせまくなって、すきまがひらく
    for i,((x0,x1),(b0,b1)) in enumerate(zip(TOP,BOT)):
        c=notex(P('布%d'%(i+1),'prism',([(x0,ZT-0.05),(x1,ZT-0.05),(x1,ZM),(b1,ZB),(b0,ZB),(x0,ZM)],CY+0.04,CY+0.052,'y'),CLOTH,on=('竿',),note='上のはしを輪で竿に通す'));c.soft1=True
        if i==1:c.decal=mark
        L.append(c)
    for k,xt in enumerate((0.04,0.31,0.69,0.96)):   # 輪：両はしと、布のさかい目に4つ（となりの布の上のはしを、いっしょにおり返す）
        L.append(notex(P('輪%d'%(k+1),'box',(xt-0.045,CY-0.04,ZT-0.06,xt+0.045,CY+0.052,ZT+0.05),CLOTH,bevel=0.01,on=('竿',),note='布の上のはしをおり返して竿に通す輪')))
    return L
