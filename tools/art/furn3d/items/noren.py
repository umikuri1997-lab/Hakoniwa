# 設計図（じっさいに作れる組み方。単位はマス。大きさは、いまの絵（80×60ドット）に合わせた。入り口の上の高い所にかける）
#   竿：まるい木の竿（半径0.03、x=-0.10〜1.10・高さ1.55）。両はしに、まるい木の玉（半径0.045）。
#   布：うすい青の布3まい（はば：まん中0.43・両がわ0.27。両がわの布は下を0.08短く。高さ1.55 → 0.74、あつさ0.012）。布のあいだは0.015あける。上のはしは、布のはしを細くおり返した輪2つ（はば0.07、高さ1.50〜1.60）で竿に通す。
#   しるし：まん中の布に、温泉のしるし（♨：上があいた、よこ長のだ円（はば0.31・高さ0.20）と、その中から立ちのぼる、ゆらゆらの湯気3本（まん中が少し高い）。クリーム色。布の面のもよう）。
from blueprint import Part as P
from common import *
import math
ID='noren';GRAD=True;PARALLEL=True;BOTTOM=-32   # 入り口の上の高い所にかけるので、絵は地面より上（いまの絵と同じ所）
VIEWS=[('noren',0)]
CY=0.55;CLOTH=(168,182,208);MARK=(244,236,214);ZT,ZB=1.55,0.74
def mark(x,y,z):   # 温泉のしるし（♨）：上があいた、よこ長のだ円（湯船）と、その中から立ちのぼる、ゆらゆらの湯気3本（まん中が少し高い）。線のはば0.024
    du,dv=(x-0.50)/0.155,(z-0.96)/0.10;a=math.degrees(math.atan2(dv,du))
    if abs(math.hypot(du,dv)-1.0)<0.15 and not(35<a<145):return MARK   # だ円（上の口はあける）
    for xc,top in((0.445,1.28),(0.50,1.31),(0.555,1.28)):
        if 0.95<z<top:
            t=(z-0.95)/(top-0.95);xw=xc+0.017*math.sin(t*2*math.pi*1.25)
            if abs(x-xw)<0.012*(1-0.35*t)+0.004:return MARK
    return None
def PARTS():
    r=P('竿','frust',((-0.10,CY,ZT),(1.10,CY,ZT),0.03,0.03),WOOD,note='入り口の上の金具にかける（金具は入り口の物）');r.deco=True;L=[r]
    for k,x in enumerate((-0.10,1.10)):L.append(P('竿の玉%d'%(k+1),'ball',(x,CY,ZT,0.045),WOOD,on=('竿',),note='竿のはし'))
    for i,(x0,x1) in enumerate(((0.0,0.27),(0.285,0.715),(0.73,1.0))):   # 布：まん中は広く（0.43）、両がわはせまく（0.27）
        zb=ZB if i==1 else ZB+0.08   # 両がわの布は、少し短く
        c=notex(P('布%d'%(i+1),'box',(x0,CY+0.04,zb,x1,CY+0.052,ZT-0.05),CLOTH,bevel=0.0,on=('竿',),note='上のはしの輪で竿に通す'));c.soft1=True
        if i==1:c.decal=mark
        L.append(c)
        for j,xt in enumerate((x0+0.035,x1-0.035)):   # 布の上のはしの、細い輪2つ
            L.append(notex(P('布の輪%d-%d'%(i+1,j+1),'box',(xt-0.035,CY-0.04,ZT-0.05,xt+0.035,CY+0.052,ZT+0.05),CLOTH,bevel=0.01,on=('竿',),note='布の上のはしを細くおり返して竿に通す輪')))
