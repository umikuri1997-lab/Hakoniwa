# 洞窟のほね（cave:bone#1）：床に半分うまった、大きな生き物のあばらぼね。見た目だけのかざり。
# 設計図（単位はマス）：おくにせぼね（太さ0.06、よこ1.2）。せぼねから手前（長い）とおく（短い）へ、弓なりの管（太さ0.04）が5本ずつ。手前ほど短い。
#   持ち主のたのみで大きく（はば1.3マス）。木と同じ5色のかげ（TONE5）。
from blueprint import Part as P
import math
ID='cave_bone1';TONE5=True;BOTTOM=56
VIEWS=[('cave:bone#1',0)]
B=(236,226,200)
def PARTS():
    L=[P('せぼね','frust',((-0.1,0.25,0.07),(1.1,0.25,0.07),0.06,0.05),B)]
    for i in range(5):   # あばら：せぼねから、横へまがりながら弓なりにのびて、先は床にうまる
        x=0.05+i*0.24;r=0.55-i*0.06
        pts=[(x+0.02,0.25,0.08)]+[(x+0.02+r*0.5*(1-math.cos(t*1.6)),0.25+r*math.sin(t*1.6)*0.9,0.08+0.2*math.sin(t*3.0)) for t in(0.25,0.5,0.75,1.0)]
        L.append(P('あばら%d1'%i,'tube',(pts,0.04),B,on=('せぼね',)))
        pts=[(x,0.25,0.08)]+[(x-0.03-r*0.25*t,0.25-r*0.4*math.sin(t*1.6),0.08+0.12*math.sin(t*3.0)) for t in(0.3,0.6,0.9)]
        L.append(P('あばら%d0'%i,'tube',(pts,0.04),B,on=('せぼね',)))
    return L
