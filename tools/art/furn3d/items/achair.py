def round_box(nm,x0,y0,x1,y1,z0,z1,col,on,note,r=0.04,bv=0.035,cloth=False):
    o=rrect(x0,y0,x1,y1,r);i_=rrect(x0+bv,y0+bv,x1-bv,y1-bv,max(0.005,r-bv/2))
    p=P(nm,'loft',[(o,z0),(o,z1-bv),(i_,z1)],col,on=on,note=note);return notex(p) if cloth else p
def PARTS():
    L=[]
    for nx,x in(('左',X0+0.01),('右',X1-0.01-LG)):
        L.append(P('前の柱（%s）'%nx,'box',(x,Y1-LG-0.02,0,x+LG,Y1-0.02,ZA),WOOD,bevel=0,note='地面にたてる。ひじかけをささえる'))
        L.append(P('うしろの柱（%s）'%nx,'box',(x,Y0+0.01,0,x+LG,Y0+0.01+LG,ZA),WOOD,bevel=0,note='地面にたてる'))
        L.append(P('よこの横木（%s）'%nx,'box',(x+0.01,Y0+0.01+LG,0.08,x+LG-0.01,Y1-LG-0.02,0.14),WOOD,on=('前の柱（%s）'%nx,'うしろの柱（%s）'%nx),bevel=0,note='前とうしろの柱のあいだ'))
