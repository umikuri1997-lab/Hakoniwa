# 布のクッションは、上から見た角も、上と下のふちも、まるく（4分の1の円で）丸める（common.py の soft）。
# 設計図（じっさいに作れる組み方。単位はマス。大きさは、いまの絵（前56×60・右49×63ドット）に合わせた）
#   柱4本：0.07角。前とうしろ、高さ0.36。地面にたてる。
#   よこの横木：前とうしろの柱のあいだ（高さ0.08〜0.14）。前の横木：前の柱のあいだ（同じ高さ）。
#   ひじかけ2本：まるいぼう（はば0.11・高さ0.07・おく0.58）。前とうしろの柱の上にのせる。
#   座板：よこの横木の上にわたす（高さ0.14〜0.17）。
#   うしろの板：はば0.68・あつさ0.08・高さ0.04〜0.43（ひじかけの高さまで）。うしろの柱にとめる。
#   背のクッション：あつさ0.15・高さ0.18〜0.70。座板にのせ、うしろの板にもたせる。10度うしろへ反らせる。
#   座のクッション：背のクッションの前、座板の上（あつさ0.10）。全体のはばは0.70。
# 後ろ向きでは、すわったせいれいの手前にうしろの板とひじかけがくるので、その絵（achair>2.front）も作る。すわった子の足は、cut でかくす。
