    L.append(notex(P('背のクッション','loft',soft(xa,ya,xb,ya+CT,0.18,ZC,0.06,0.05,10),CLOTH,on=('座板','うしろの板'),note='座板にのせ、うしろの板にもたせる。10度反らせる')))
    return L
