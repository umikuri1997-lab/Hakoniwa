# つぼ（rockart）：いまの絵と同じデザイン・同じ大きさ。素焼きの、ふっくらしたつぼ。上がふくらみ、首がしまって、口のふちが外へひらく。
# 設計図（じっさいに作れる組み方。単位はマス。大きさは、いまの絵（46×62ドット）に合わせた）
#   つぼ：ろくろでひいた1つの形（底の半径0.17・いちばん太い所の半径0.33（高さ0.328）・首の半径0.175（高さ0.55）・口のふちの半径0.22（高さ0.59））。
#     かべのあつさ0.05。中は、底（高さ0.066）までへこむ。地面におく。
#   口のふち：口のまわりに、まるめた土をつけたふち（半径0.165〜0.24・高さ0.565〜0.61）。
#   中の面：光がとどかないので、外よりくらい（口の近く → 底へ、だんだんくらく）。
#   色：あたたかい素焼きの色（TERRA）。
from blueprint import Part as P
from common import *
import math
ID='rockart';BOTTOM=45;GRAD=True
VIEWS=[('rockart',0)]
CX,CY=0.50,0.52;TERRA=(230,190,142)
INLIT=(186,146,108);INDARK=(146,112,86)   # 中の面の色（口の近く → 底）
OUT=[(0.17,0.0),(0.23,0.049),(0.29,0.139),(0.325,0.246),(0.33,0.328),(0.31,0.41),(0.26,0.484),(0.19,0.53),(0.175,0.55),(0.205,0.575),(0.22,0.59)]   # 外の面（底のふちから口のふちまで）
PROF=[(0.0,0.0)]+OUT+[(0.18,0.594),(0.14,0.566),(0.145,0.525),(0.21,0.476),(0.26,0.402),(0.28,0.328),(0.27,0.246),(0.24,0.139),(0.17,0.066),(0.0,0.066)]
def PARTS():
    p=P('つぼ','lathe',(CX,CY,PROF),TERRA,detail=48,note='地面におく。ろくろでひいた1つの形');p.tex=False
    def rout(z):
        for (r0,a),(r1,b) in zip(OUT,OUT[1:]):
            if a<=z<=b:return r0+(r1-r0)*(z-a)/max(1e-9,b-a)
        return OUT[-1][0]
    def col(x,y,z):
        if math.hypot(x-CX,y-CY)<rout(z)-0.03:   # 中の面：光がとどかず、くらい。底ほどくらい
            t=max(0,min(1,(z-0.066)/0.51));return tuple(INDARK[k]+(INLIT[k]-INDARK[k])*t for k in range(3))
        return None
    p.decal=col
    q=P('口のふち','lathe',(CX,CY,[(0.165,0.565),(0.215,0.565),(0.24,0.578),(0.24,0.598),(0.215,0.61),(0.165,0.61)]),TERRA,detail=40,on=('つぼ',),note='口のまわりに、ひもの形にまるめた土をつけたふち');p2=q;q.tex=False
    return [p,q]
