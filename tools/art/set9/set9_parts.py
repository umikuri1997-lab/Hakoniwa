def arch():
    X0,X1,Y0,Y1,H=-0.22,1.22,0.18,0.82,1.55;T=0.11;L=[]
    for sx,x in(('左',X0),('右',X1-T)):
        for sy,y in(('うしろ',Y0),('前',Y1-T)):L.append(P('柱（%s%s）'%(sx,sy),'box',(x,y,0,x+T,y+T,H),WOOD2,note='地面にうめる'))
        for i,z in enumerate((0.35,0.75,1.15)):L.append(P('横の桟（%s%d）'%(sx,i+1),'box',(x+0.02,Y0+T,z,x+T-0.02,Y1-T,z+0.05),WOOD,on=('柱（%sうしろ）'%sx,'柱（%s前）'%sx)))
        for i,y in enumerate((Y0+0.24,Y1-0.29)):L.append(P('たての桟（%s%d）'%(sx,i+1),'box',(x+0.03,y,0.3,x+T-0.03,y+0.04,1.2),WOOD,on=('横の桟（%s1）'%sx,)))
    for sy,y in(('うしろ',Y0),('前',Y1-T)):L.append(P('桁（%s）'%sy,'box',(X0-0.16,y,H,X1+0.16,y+T,H+0.14),WOOD,on=('柱（左%s）'%sy,'柱（右%s）'%sy),note='はしが外へ出る'))
    for i in range(7):
        x=X0-0.06+i*(X1-X0+0.05)/6;L.append(P('横木%d'%(i+1),'box',(x,Y0-0.14,H+0.14,x+0.07,Y1+0.14,H+0.22),WOOD2,on=('桁（うしろ）','桁（前）')))
    import random;rd=random.Random(3)
    for k in range(26):
        if k<14:x=X1-0.04+rd.uniform(-0.06,0.06);y=rd.uniform(Y0,Y1);z=rd.uniform(0.15,H)
        else:x=rd.uniform(0.4,X1+0.1);y=rd.uniform(Y0-0.05,Y1+0.05);z=H+0.25
        L.append(P('つるバラ','ball',(x,y,z,rd.uniform(0.07,0.11)),LEAF,deco=True))
        if k%3==0:L.append(P('つるバラ','ball',(x+0.02,y+0.06,z+0.04,0.045),FLOW,deco=True))
    return L

def slide():
    # 2×2マス。左に階段、まん中に台、右へすべり面。台は4本の柱と、前・うしろのはりにのる
    DX0,DX1,DY0,DY1,DZ=0.45,1.05,1.0,1.8,0.7;T=0.09;CY=(DY0+DY1)/2
    L=[]
    for sx,x in(('左',DX0),('右',DX1-T)):
        for sy,y in(('うしろ',DY0),('前',DY1-T)):L.append(P('柱（%s%s）'%(sx,sy),'box',(x,y,0,x+T,y+T,DZ+0.42),WOOD2,note='地面にうめる'))
    for sy,y in(('うしろ',DY0),('前',DY1-T)):L.append(P('はり（%s）'%sy,'box',(DX0,y,DZ-0.08,DX1,y+T,DZ),WOOD,on=('柱（左%s）'%sy,'柱（右%s）'%sy)))
    L.append(P('台の床板','box',(DX0,DY0,DZ,DX1,DY1,DZ+0.06),WOOD,on=('はり（うしろ）','はり（前）')))
    for sy,y in(('うしろ',DY0),('前',DY1-0.05)):
        for i,z in enumerate((DZ+0.18,DZ+0.36)):L.append(P('手すり（%s%d）'%(sy,i+1),'box',(DX0,y,z,DX1,y+0.05,z+0.05),WOOD,on=('柱（左%s）'%sy,'柱（右%s）'%sy)))
    # 階段：2まいの側げた（ななめの板）に、ふみ板4まい
    for sy,y in(('うしろ',DY0+0.12),('前',DY1-0.12)):
        L.append(P('側げた（%s）'%sy,'plate',((DX0,y,DZ),(0.0,y,0.0),0.04,0.12),WOOD2,on=('はり（うしろ）','はり（前）','ground'),note='上は台のはり、下は地面'))
    for i in range(1,5):
        z=DZ*i/5;xc=DX0*z/DZ;L.append(P('ふみ板%d'%i,'box',(xc-0.07,DY0+0.1,z-0.03,xc+0.07,DY1-0.1,z+0.01),WOOD,on=('側げた（うしろ）','側げた（前）')))
    for sy,y in(('うしろ',DY0),('前',DY1-0.06)):
        L.append(P('親柱（%s）'%sy,'box',(0.0,y,0,0.06,y+0.06,0.45),WOOD2,note='地面にうめる'))
        L.append(P('階段の手すり（%s）'%sy,'beam',((0.03,y+0.03,0.45),(DX0+0.04,y+0.03,DZ+0.4),0.025),WOOD,on=('親柱（%s）'%sy,'柱（左%s）'%sy)))
    # すべり面：台の右のはしにかけ、下は2本の足にのる。両がわにかべ
    a=(DX1,CY,DZ+0.03);b=(1.82,CY,0.16);c=(2.0,CY,0.16)
    L.append(P('すべり面','plate',(a,b,0.5,0.03),SAND,on=('台の床板','足（うしろ）','足（前）'),note='台にかける'))
    L.append(P('すべり出し','plate',(b,c,0.5,0.03),SAND,on=('足（うしろ）','足（前）')))
    for sy,yy in(('うしろ',CY-0.26),('前',CY+0.26)):
        L.append(P('かべ（%s）'%sy,'plate',((a[0],yy,a[2]+0.07),(b[0],yy,b[2]+0.07),0.03,0.12),(222,196,150),on=('すべり面',)))
        L.append(P('かべ（%s2）'%sy,'plate',((b[0],yy,b[2]+0.07),(c[0],yy,c[2]+0.07),0.03,0.12),(222,196,150),on=('すべり出し',)))
        L.append(P('足（%s）'%sy,'box',(1.8,yy-0.04 if sy=='うしろ' else yy-0.04,0,1.88,yy+0.04,0.15),WOOD2,note='地面にうめる'))
    return L

