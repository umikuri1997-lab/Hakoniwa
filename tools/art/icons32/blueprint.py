#!/usr/bin/env python3
"""設計図のアイコン（どの設計図も同じ絵。持ち主がえらんだ）。
32×32 のドット絵を手で描き、ほかのアイコン（宝の地図・手紙）と同じに、ドットを3つずつにのばした 96×96 を assets/g に入れ、
js/draw-spirits.js の ICONS の bp に書く。前の絵のファイルは消す。
絵：あわい青の方眼の紙（持ち主のたのみで、あわい色に）。上のはしは、まるめた紙（筒）。右下のすみは、少しめくれてうらが見える。紙には白い線で家（屋根・かべ・戸・窓）と寸法の線。
かげは明度でなく彩度で（art.md）。
  python3 tools/art/icons32/blueprint.py [見本の出力フォルダ]"""
import os, sys, io, re, hashlib
from PIL import Image
D = os.path.dirname(os.path.abspath(__file__)); R = os.path.abspath(os.path.join(D, '..', '..', '..'))
PAL = {
 'K': (62, 92, 150),     # 輪郭（中より少しこい青）
 'B': (120, 164, 222),    # 紙
 'S': (104, 156, 228),    # 紙のかげ（あざやか）
 'g': (146, 184, 232),   # 方眼の線
 'W': (246, 250, 255),  # 白い線
 'w': (206, 224, 248),  # 白い線のかげ・寸法の線
 'R': (160, 196, 240),   # 筒の明るい所
 'r': (128, 170, 228),   # 筒
 'H': (214, 232, 252),  # 筒のハイライト
 'U': (196, 216, 244),  # めくれたうら
 'u': (170, 198, 238),  # めくれたうらのかげ
}
ART = """
................................
................................
................................
................................
...KKKKKKKKKKKKKKKKKKKKKKKKKK...
..KHHHHHHHHHHHHHHHHHHHHHHHHHRK..
..KRRRRRRRRRRRRRRRRRRRRRRRRRrK..
..KrrrrrrrrrrrrrrrrrrrrrrrrrrK..
...KKKKKKKKKKKKKKKKKKKKKKKKKK...
....KBBBgBBBgBBBgBBBgBBBgBBSK...
....KBBBgBBBgBBBgBWBgBBBgBBSK...
....KggggggggggggWgWgggggggSK...
....KBBBgBBBgBBBWBBBWBBBgBBSK...
....KBBBgBBBgBBWgBBBgWBBgBBSK...
....KBBBgBBBgBWBgBBBgBWBgBBSK...
....KggggggggWgggggggggWgggSK...
....KBBBgBBBWWWWWWWWWWWWWBBSK...
....KBBBgBBBgWBBgBBBgBBWgBBSK...
....KBBBgBBBgWBWWWBWWWBWgBBSK...
....KggggggggWgWgWgWgWgWgggSK...
....KBBBgBBBgWBWWWBWgWBWgBBSK...
....KBBBgBBBgWBBgBBWgWBWgBBSK...
....KBBBgBBBgWWWWWWWWWWWgBBSK...
....KggggggggggggggggggggggSK...
....KBBBgBBBgwBBgBBBgBBwKKKKK...
....KBBBgBBBgwwwwwwwwwwwKUUuK...
....KBBBgBBBgwBBgBBBgBBwKUuK....
....KSSSSSSSSSSSSSSSSSSSKuK.....
....KKKKKKKKKKKKKKKKKKKKKK......
................................
................................
................................
"""
def draw():
    rows = [r for r in ART.strip('\n').split('\n')]
    assert len(rows) == 32 and all(len(r) == 32 for r in rows), [len(r) for r in rows]
    im = Image.new('RGBA', (32, 32), (0, 0, 0, 0)); px = im.load()
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c != '.': px[x, y] = PAL[c] + (255,)
    return im
if __name__ == '__main__':
    im = draw()
    if len(sys.argv) > 1:
        os.makedirs(sys.argv[1], exist_ok=True)
        im.resize((320, 320), Image.NEAREST).save(os.path.join(sys.argv[1], 'blueprint_x10.png')); sys.exit()
    big = im.resize((96, 96), Image.NEAREST); b = io.BytesIO(); big.save(b, 'WEBP', lossless=True, exact=True); data = b.getvalue()
    name = 'assets/g/' + hashlib.sha1(data).hexdigest()[:10] + '.webp'; open(os.path.join(R, name), 'wb').write(data)
    js = os.path.join(R, 'js', 'draw-spirits.js'); s = open(js, encoding='utf-8').read()
    m = re.search(r"\bbp:'(assets/g/[0-9a-f]+\.webp)'", s)
    if m:
        old = m.group(1)
        if old != name and os.path.exists(os.path.join(R, old)): os.remove(os.path.join(R, old))
        s = s[:m.start()] + "bp:'%s'" % name + s[m.end():]
    else:
        s = s.replace("const ICONS={", "const ICONS={bp:'%s',/* 設計図（tools/art/icons32/blueprint.py） */" % name, 1)
    open(js, 'w', encoding='utf-8').write(s); print('アイコン bp', name)
