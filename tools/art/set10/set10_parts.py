# 8つの物（ベンチ・キャビネット・かざり棚・本棚・木箱・食料箱・かべ棚・とげの罠）の設計図（部品の表）。tools/art/blueprint.py の Part で書く。
# この表から、設計図（ref/bp_<n>_<id>.png）と3D（set10_3d.py）の両方を作る。数字はマス（x=東, y=南, z=上、置くマスの左上が(0,0)）。
# 大きさ・置く所は、いまの絵に合わせる。部品は、じっさいに作るときと同じように、何にのる・何にとめるか（on）を書く。
from blueprint import Part as P
WOOD=(214,170,120);WOOD2=(190,146,100);WOOD3=(170,128,88);LEAF=(150,200,110);CLAY=(236,224,200);BLUE=(160,180,210)
BOOKS=[(200,150,140),(150,175,205),(160,190,150),(230,210,160),(190,165,200),(225,175,140)]
WALL=(225,225,232);VEG=[(240,150,70),(140,200,110),(220,80,70),(240,200,90)]

def legs4(L,x0,x1,y0,y1,z1,t,col=WOOD2,on=('ground',)):
    for sx,x in(('左',x0),('右',x1-t)):
        for sy,y in(('うしろ',y0),('前',y1-t)):L.append(P('脚（%s%s）'%(sx,sy),'box',(x,y,0,x+t,y+t,z1),col,on=on))

def bench():
    # 2×1マス。せもたれのない木のベンチ：あつい座板を、4本の脚と前後の幕板でささえる
    L=[];legs4(L,0.1,1.9,0.5,0.98,0.38,0.1)
    for sy,y in(('うしろ',0.52),('前',0.92)):L.append(P('幕板（%s）'%sy,'box',(0.12,y,0.28,1.88,y+0.04,0.38),WOOD2,on=('脚（左%s）'%sy,'脚（右%s）'%sy),note='脚にほぞでとめる'))
    L.append(P('座板','box',(0.02,0.42,0.38,1.98,1.0,0.5),WOOD,on=('脚（左前）','脚（右前）','脚（左うしろ）','脚（右うしろ）'),note='はしは少し外へ出す'))
    return L

def cabinet():
    # とびら2まいの低い棚。台わの上に箱、天板は少し外へ出す
    L=[];legs4(L,0.04,0.96,0.24,0.6,0.06,0.08)
    L.append(P('本体（側板・底板・背板）','box',(0.0,0.22,0.06,1.0,0.6,0.7),WOOD,on=('脚（左前）','脚（右前）','脚（左うしろ）','脚（右うしろ）')))
    L.append(P('天板','box',(-0.03,0.19,0.7,1.03,0.63,0.76),WOOD,on=('本体（側板・底板・背板）',),note='まわりへ少し出す'))
    for sx,x in(('左',0.06),('右',0.51)):
        L.append(P('とびら（%s）'%sx,'box',(x,0.6,0.1,x+0.43,0.62,0.64),WOOD2,on=('本体（側板・底板・背板）',),note='ちょうつがいで本体の前にとめる'))
        L.append(P('とびらのくぼみ（%s）'%sx,'box',(x+0.06,0.62,0.18,x+0.37,0.625,0.56),WOOD3,deco=True))
    for x in(0.44,0.53):L.append(P('とってのつまみ','ball',(x+0.015,0.64,0.42,0.025),WOOD3,deco=True))
    return L

def shelf2():
    # かざり棚：四すみの柱に、棚板4まい（背板なし）。棚に、つぼ・はち植え・びん・本をかざる
    L=[];X0,X1,Y0,Y1,H=0.02,0.98,0.3,0.68,1.36
    legs4(L,X0,X1,Y0,Y1,H,0.07)
    for i,z in enumerate((0.1,0.5,0.9,1.3)):L.append(P('棚板%d'%(i+1),'box',(X0,Y0,z,X1,Y1,z+0.05),WOOD,on=('脚（左前）','脚（右前）','脚（左うしろ）','脚（右うしろ）'),note='柱にみぞをほってはめる'))
    D=[('つぼ','cyl',(0.32,0.48,0.12,1.35,1.55),CLAY),('はち植えのはち','cyl',(0.68,0.48,0.1,1.35,1.47),CLAY),('はち植えの葉','ball',(0.68,0.48,1.55,0.15),LEAF),
       ('はち植えの葉','ball',(0.3,0.48,0.75,0.17),LEAF),('びん','cyl',(0.7,0.48,0.11,0.95,1.18),BLUE),('つぼ','cyl',(0.3,0.48,0.1,0.15,0.36),CLAY),('かさねた本','box',(0.5,0.36,0.15,0.88,0.62,0.3),BOOKS[1])]
    for nm,k,d,c in D:L.append(P(nm,k,d,c,deco=True,detail=16))
    return L

def shelf1():
    # 本棚：側板2まい・天板・地板・背板の箱に、棚板2まい。本がならぶ
    L=[];X0,X1,Y0,Y1=0.02,0.98,0.32,0.68
    legs4(L,X0+0.04,X1-0.04,Y0+0.02,Y1-0.02,0.06,0.08)
    L.append(P('地板','box',(X0,Y0,0.06,X1,Y1,0.12),WOOD,on=('脚（左前）','脚（右前）','脚（左うしろ）','脚（右うしろ）')))
    for sx,x in(('左',X0),('右',X1-0.06)):L.append(P('側板（%s）'%sx,'box',(x,Y0,0.12,x+0.06,Y1,1.36),WOOD,on=('地板',)))
    L.append(P('背板','box',(X0+0.06,Y0,0.12,X1-0.06,Y0+0.03,1.36),WOOD2,on=('地板',)))
    L.append(P('天板','box',(X0-0.03,Y0-0.02,1.36,X1+0.03,Y1+0.03,1.42),WOOD,on=('側板（左）','側板（右）'),note='まわりへ少し出す'))
    for i,z in enumerate((0.5,0.92)):L.append(P('棚板%d'%(i+1),'box',(X0+0.06,Y0+0.03,z,X1-0.06,Y1,z+0.05),WOOD,on=('側板（左）','側板（右）'),note='側板にだぼでとめる'))
    for z0 in(0.12,0.55,0.97):
        x=0.1
        for k in range(9):
            w=0.075+0.012*(k%3);h=0.28+0.05*((k*7)%3)
            if x+w>0.9:break
            L.append(P('本','box',(x,Y0+0.06,z0,x+w,Y1-0.04,z0+h),BOOKS[(k+int(z0*10))%6],deco=True));x+=w+0.008
    return L

