def legs4(L,x0,x1,y0,y1,z0,z1,t,col=WOOD2,on=('ground',),bevel=None):
    for sx,x in(('左',x0),('右',x1-t)):
        for sy,y in(('うしろ',y0),('前',y1-t)):L.append(P('脚（%s%s）'%(sx,sy),'box',(x,y,z0,x+t,y+t,z1),col,on=on,bevel=bevel))
def planks(L,nm,x0,x1,y0,y1,z0,z1,n,axis,col=WOOD,on=('ground',),gap=0.012,bevel=0.012):
    """板をならべる。axis：'x' は東西にならべる（板はたて長）、'z' は上下にならべる（横板）、'y' は南北にならべる"""
    for i in range(n):
        if axis=='x':a=x0+(x1-x0)*i/n;b=x0+(x1-x0)*(i+1)/n-gap;L.append(P('%s%d'%(nm,i+1),'box',(a,y0,z0,b,y1,z1),col,on=on,bevel=bevel))
        elif axis=='y':a=y0+(y1-y0)*i/n;b=y0+(y1-y0)*(i+1)/n-gap;L.append(P('%s%d'%(nm,i+1),'box',(x0,a,z0,x1,b,z1),col,on=on,bevel=bevel))
        else:a=z0+(z1-z0)*i/n;b=z0+(z1-z0)*(i+1)/n-gap;L.append(P('%s%d'%(nm,i+1),'box',(x0,y0,a,x1,y1,b),col,on=on,bevel=bevel))

