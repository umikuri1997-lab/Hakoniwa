/* ---------- クォータービューの、せいれい・生き物・コワイノの向き（PR6） ----------
   せかいの向きは、いままでどおり（正面＝南・うしろ＝北・よこ＝東西）。クォータービューの画面では、どれもななめになる：
     南（正面）→ 左下・東（右）→ 右下・北（うしろ）→ 右上・西（左）→ 左上
   絵は2つだけ：前ななめ（南を向いた物を iso3d.py で写す＝左下を向く）と、うしろななめ（北を向く＝右上を向く）。東・西は、それを左右に反転する。
   絵の名前は、いまの正面の絵（せいれいの動きの正面の行・生き物の #d・コワイノの <動き>）を前ななめに、
   うしろの絵（うしろの行・#u・<動き>B）をうしろななめに入れかえる。よこの絵（よこの行・生き物の #<コマ>・コワイノの R・L）は、クォータービューでは使わない。
   絵がとどくまでは、いまの正面・うしろの絵をそのまま使う（仮）。 */
/* せかいの向き → 画面の絵。back：うしろの絵か・side：よこを向いているか・f：よこの向き（1 東・−1 西）。かえすのは {back, f}（f：−1 で反転） */
function isoFace(back,side,f){if(side)return{back:f<0,f:-1};return{back:!!back,f:1}}
